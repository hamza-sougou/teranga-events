// Centralized React Query key builders so the events list, the edit page,
// and the ticket-type/whitelist modals all invalidate exactly the same
// cache entries — a typo'd literal key array is otherwise an easy silent bug
// across that many call sites.
export const queryKeys = {
  events: (organizationId?: string) => ['org-events', organizationId],
  event: (organizationId?: string, eventId?: string) => ['org-event', organizationId, eventId],
  ticketTypes: (organizationId?: string, eventId?: string) => ['org-ticket-types', organizationId, eventId],
  whitelist: (organizationId?: string, eventId?: string, ticketTypeId?: string) => [
    'org-ticket-type-whitelist',
    organizationId,
    eventId,
    ticketTypeId,
  ],
  orgStats: (organizationId?: string) => ['org-stats', organizationId],
  media: (organizationId?: string, eventId?: string) => ['org-event-media', organizationId, eventId],
  eventCategories: () => ['event-categories'],
  orders: (organizationId?: string, eventId?: string) => ['org-event-orders', organizationId, eventId],
  scans: (organizationId?: string, eventId?: string) => ['org-event-scans', organizationId, eventId],
  teamMembers: (organizationId?: string) => ['org-team-members', organizationId],
  payoutsOverview: (organizationId?: string) => ['org-payouts-overview', organizationId],
  orgProfile: (organizationId?: string) => ['org-profile', organizationId],
  publicEvent: (slug?: string) => ['public-event', slug],
  publicTicketTypes: (slug?: string) => ['public-ticket-types', slug],
  discoverTrending: () => ['discover-trending'],
  discoverThisWeekend: () => ['discover-this-weekend'],
  discoverNearMe: (lat?: number, lng?: number) => ['discover-near-me', lat, lng],
  discoverSponsored: () => ['discover-sponsored'],
  discoverRecentlyPublished: () => ['discover-recently-published'],
  discoverLastChance: () => ['discover-last-chance'],
  discoverFree: () => ['discover-free'],
  orderPreview: (eventId?: string, itemsKey?: string) => ['order-preview', eventId, itemsKey],
  publicOrder: (orderId?: string) => ['public-order', orderId],
  adminOrganizations: () => ['admin-organizations'],
  adminOrgMembers: (organizationId?: string) => ['admin-org-members', organizationId],
  adminEvents: (filters?: Record<string, string | undefined>) => ['admin-events', filters],
};
